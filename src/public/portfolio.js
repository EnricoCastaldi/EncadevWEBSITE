const chartDetail = document.querySelector("#chart-detail");
const metric = document.querySelector("#metric");
let selectedWeek = 5;
const chartBars = metrics.orders.map((_, index) => {
  const button = document.createElement("button");
  const bar = document.createElement("i");
  const caption = document.createElement("span");
  button.type = "button";
  bar.setAttribute("aria-hidden", "true");
  caption.setAttribute("aria-hidden", "true");
  button.append(bar, caption);
  button.addEventListener("click", () => {
    selectedWeek = index;
    renderChart();
  });
  chart.append(button);
  return { button, bar, caption };
});

function renderChart() {
  const values = metrics[metric.value];
  const format = saleFormatter(metric.value);
  const total = values.reduce((sum, value) => sum + value, 0);
  const maximum = Math.max(...values);
  chartTotal.textContent = format.format(total);
  chartAverage.textContent = format.format(Math.round(total / values.length));
  chartPeak.textContent = format.format(maximum);
  document.querySelector("#channel-total").textContent = saleFormatter("orders").format(channelTotal);
  chartTrend.setAttribute("points", values.map((value, index) =>
    ((index + 0.5) * 600 / values.length) + "," + (100 - value / maximum * 90)
  ).join(" "));
  const metricLabel = t(metric.value === "orders" ? "Orders" : "Revenue");
  chartBars.forEach(({ button, bar, caption }, index) => {
    bar.style.setProperty("--bar", (values[index] / maximum * 90) + "%");
    caption.textContent = (language === "pl" ? "T" : "W") + (index + 1);
    const detail = t("Week") + " " + (index + 1) + " · " + metricLabel + " · " + format.format(values[index]);
    button.setAttribute("aria-label", detail);
    button.title = detail;
    button.setAttribute("aria-pressed", String(index === selectedWeek));
    if (index === selectedWeek) chartDetail.textContent = detail;
  });
}
metric.addEventListener("change", renderChart);

