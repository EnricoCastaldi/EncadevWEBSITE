function renderTickets() {
  for (const button of ticketStatusButtons) {
    const status = button.dataset.ticketStatus;
    button.querySelector("strong").textContent = tickets.filter((ticket) => ticket[3] === status).length;
    button.setAttribute("aria-pressed", String(ticketFilter.value === status));
  }
  const rows = tickets.filter((ticket) => ticketFilter.value === "all" || ticket[3] === ticketFilter.value)
    .map(([id, subject, team, status]) => {
      const row = document.createElement("tr");
      const ticket = row.insertCell();
      const reference = document.createElement("small");
      reference.className = "ticket-reference";
      reference.textContent = "#" + id;
      ticket.append(reference, document.createTextNode(t(subject)));
      row.insertCell().textContent = t(team);
      const badge = document.createElement("span");
      badge.className = "ticket-badge";
      badge.dataset.status = status;
      badge.textContent = t(statuses[status]);
      row.insertCell().append(badge);
      return row;
    });
  ticketList.replaceChildren(...rows);
}
