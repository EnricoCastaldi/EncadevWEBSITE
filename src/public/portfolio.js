function saleFormatter(metricName) {
  const locale = language === "pl" ? "pl-PL" : "en-GB";
  const options = metricName === "revenue"
    ? { style: "currency", currency: "PLN", maximumFractionDigits: 0 }
    : {};
  return new Intl.NumberFormat(locale, options);
}

function demoRow(heading, values) {
  const row = document.createElement("tr");
  const header = document.createElement("th");
  header.scope = "row";
  header.textContent = heading;
  row.append(header);
  for (const value of values) row.insertCell().textContent = value;
  return row;
}

const weeklyReport = document.querySelector("#weekly-report");
const teamWorkload = document.querySelector("#team-workload");
const role = document.querySelector("#demo-role");
const permissions = document.querySelector("#demo-permissions");
const accessRules = ["View tickets", "Change ticket status", "Manage team access"];
const allowedCount = { viewer: 1, agent: 2, admin: 3 };
const handoffTopic = document.querySelector("#handoff-topic");
const handoffResult = document.querySelector("#handoff-result");
const handoffTeams = { delivery: "Operations", account: "Support", billing: "Finance" };
let previewedTopic;

function renderPermissions() {
  const items = accessRules.map((permission, index) => {
    const allowed = index < allowedCount[role.value];
    const item = document.createElement("li");
    const label = document.createElement("span");
    const state = document.createElement("strong");
    label.textContent = t(permission);
    state.textContent = t(allowed ? "Allowed" : "Restricted");
    state.className = allowed ? "allowed" : "restricted";
    item.append(label, state);
    return item;
  });
  permissions.replaceChildren(...items);
}

function renderHandoff() {
  if (!previewedTopic) {
    handoffResult.replaceChildren();
    return;
  }
  const team = document.createElement("strong");
  const message = document.createElement("p");
  team.textContent = t("Assigned team") + " · " + t(handoffTeams[previewedTopic]);
  message.textContent = t("The sample conversation and selected topic would be included.");
  handoffResult.replaceChildren(team, message);
}

function renderDemoScreens() {
  const orders = saleFormatter("orders");
  const revenue = saleFormatter("revenue");
  weeklyReport.replaceChildren(...metrics.orders.map((value, index) =>
    demoRow(t("Week") + " " + (index + 1), [orders.format(value), revenue.format(metrics.revenue[index])])
  ));

  const teams = [...new Set(tickets.map((ticket) => ticket[2]))];
  teamWorkload.replaceChildren(...teams.map((team) =>
    demoRow(t(team), Object.keys(statuses).map((status) =>
      tickets.filter((ticket) => ticket[2] === team && ticket[3] === status).length
    ))
  ));
  renderPermissions();
  renderHandoff();
}

role.addEventListener("change", renderPermissions);
handoffTopic.addEventListener("change", () => {
  previewedTopic = undefined;
  renderHandoff();
});
document.querySelector("#handoff-preview").addEventListener("click", () => {
  previewedTopic = handoffTopic.value;
  renderHandoff();
});

