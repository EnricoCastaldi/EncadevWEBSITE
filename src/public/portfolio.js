const choiceKey = "encadev-privacy-choice";
const languageKey = "encadev-language";
const choiceLifetime = 180 * 24 * 60 * 60 * 1000;

function storedCookieChoice() {
  try {
    const stored = JSON.parse(localStorage.getItem(choiceKey));
    if (stored?.expires > Date.now() && ["essential", "language"].includes(stored.choice)) {
      return stored.choice;
    }
    localStorage.removeItem(choiceKey);
    localStorage.removeItem(languageKey);
  } catch {
    localStorageCleanup();
  }
  return null;
}

function localStorageCleanup() {
  try {
    localStorage.removeItem(choiceKey);
    localStorage.removeItem(languageKey);
  } catch {
    // The site also works with storage blocked.
  }
}

let cookieChoice = storedCookieChoice();

function preferredLanguage() {
  if (cookieChoice !== "language") return navigator.language.toLowerCase().startsWith("pl") ? "pl" : "en";
  try {
    const saved = localStorage.getItem(languageKey);
    if (saved === "pl" || saved === "en") return saved;
  } catch {
    // Language selection still works when browser storage is disabled.
  }
  return navigator.language.toLowerCase().startsWith("pl") ? "pl" : "en";
}

let language = preferredLanguage();
const t = (copy) => language === "pl" ? polish[copy] ?? copy : copy;
const localizedText = [...document.querySelectorAll("[data-copy]")].map((element) => [element, element.textContent.trim()]);
const localizedLabels = [...document.querySelectorAll("[aria-label]:not([data-lang])")].map((element) => [element, element.getAttribute("aria-label")]);
const languageButtons = [...document.querySelectorAll("[data-lang]")];
