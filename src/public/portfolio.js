const chatLog = document.querySelector("#chat-log");
let currentPrompt;

function chatMessage(copy, visitor = false) {
  const message = document.createElement("div");
  message.className = visitor ? "chat-message visitor" : "chat-message";
  const avatar = document.createElement("span");
  avatar.className = "chat-avatar";
  avatar.setAttribute("aria-hidden", "true");
  avatar.textContent = visitor ? "●" : "✦";
  const bubble = document.createElement("p");
  bubble.textContent = t(copy);
  message.append(avatar, bubble);
  return message;
}

function renderChat() {
  const messages = [chatMessage("Hi! What can I help you with?")];
  if (currentPrompt) {
    const [question, reply] = chatReplies[currentPrompt];
    messages.push(chatMessage(question, true), chatMessage(reply));
  }
  chatLog.replaceChildren(...messages);
  for (const button of chatPrompts) {
    button.setAttribute("aria-pressed", String(button.dataset.prompt === currentPrompt));
  }
}
const chatPrompts = [...document.querySelectorAll("[data-prompt]")];
for (const button of chatPrompts) {
  button.addEventListener("click", () => {
    currentPrompt = button.dataset.prompt;
    renderChat();
    chatLog.scrollTop = chatLog.scrollHeight;
  });
}

const stack = document.querySelector("#stack-items");
const stackSection = stack.closest(".stack");
let carouselVisible = false;
let carouselLimit = 0;
let carouselDirection = 1;
let carouselPosition = null;
let carouselResumeTime = 0;

function advanceCarousel(time, delta) {
  if (!carouselVisible || carouselLimit < 1 || time < carouselResumeTime ||
      stackSection.matches(":hover, :focus-within")) {
    carouselPosition = null;
    return;
  }

  if (carouselPosition === null) carouselPosition = stack.scrollLeft;
  const distanceToEdge = carouselDirection > 0 ? carouselLimit - carouselPosition : carouselPosition;
  const speed = Math.min(42, 12 + distanceToEdge * 0.8);
  carouselPosition += carouselDirection * speed * delta;

  if (carouselPosition >= carouselLimit || carouselPosition <= 0) {
    carouselPosition = Math.max(0, Math.min(carouselLimit, carouselPosition));
    carouselDirection = carouselPosition === 0 ? 1 : -1;
    carouselResumeTime = time + 850;
  }

  stack.scrollLeft = carouselPosition;
}


new ResizeObserver(() => {
  carouselLimit = Math.max(0, stack.scrollWidth - stack.clientWidth);
  carouselPosition = null;
}).observe(stack);

new IntersectionObserver(([entry]) => {
  carouselVisible = entry.isIntersecting;
}).observe(stack);

