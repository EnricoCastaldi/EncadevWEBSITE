function applyLanguage() {
  document.documentElement.lang = language;
  document.title = t(baseTitle);
  description.content = t(baseDescription);
  for (const [element, copy] of localizedText) element.textContent = t(copy);
  for (const [element, label] of localizedLabels) element.setAttribute("aria-label", t(label));
  for (const button of languageButtons) button.setAttribute("aria-pressed", String(button.dataset.lang === language));
  renderChart();
  renderTickets();
  renderChat();
  renderDemoScreens();
}

for (const button of languageButtons) {
  button.addEventListener("click", () => {
    language = button.dataset.lang;
    try {
      if (cookieChoice === "language") localStorage.setItem(languageKey, language);
    } catch {
      // Keep the selection for the current visit.
    }
    applyLanguage();
    document.dispatchEvent(new Event("languagechange"));
  });
}

