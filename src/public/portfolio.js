const chartTotal = document.querySelector("#chart-total");
const chartAverage = document.querySelector("#chart-average");
const chartPeak = document.querySelector("#chart-peak");
const chartTrend = chart.querySelector("polyline");
const donut = document.querySelector(".demo-donut");
const channelValues = [...document.querySelectorAll(".channel-list progress")].map((progress) => progress.value);
